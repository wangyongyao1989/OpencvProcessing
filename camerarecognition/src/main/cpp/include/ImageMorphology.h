#ifndef OPENCVDEAL_IMAGEMORPHOLOGY_H
#define OPENCVDEAL_IMAGEMORPHOLOGY_H

#include <opencv2/core.hpp>

/**
 * 形态学图像处理
 *
 * 基于《数字图像与视频处理》第 3 章"形态学图像处理"实现：
 * - 3.2 二值形态学基本运算：腐蚀（式 3-9）、膨胀（式 3-10/3-11）、
 *   开运算（式 3-15/3-16）、闭运算（式 3-17~3-19）、对偶性（式 3-13/3-14）
 * - 3.3 二值图像的形态学处理：边缘提取（式 3-20~3-22）、区域填充（式 3-23）、
 *   骨架抽取（式 3-24~3-28）、细化（式 3-29~3-31）、噪声滤除（式 3-34/3-35）
 * - 3.4 灰度形态学基本运算：灰度腐蚀（式 3-36/3-37）、灰度膨胀（式 3-38/3-39）、
 *   对偶（式 3-40/3-41）、灰度开（式 3-42）、灰度闭（式 3-43~3-45）
 * - 3.5 灰度图像的形态学处理：形态学梯度（式 3-46）、
 *   形态学平滑（式 3-47/3-48）、高帽 Top-Hat（式 3-49）、低帽（表 3-1 bothat）
 *
 * 二值运算的输入为彩色/灰度照片时，内部先以 Otsu 自动二值化（前景 255）。
 */
namespace ImageMorphology {

    // =====================================================================
    // 通用
    // =====================================================================

    /** Otsu 自动阈值二值化（前景=255，背景=0），作为二值形态学运算的预处理。 */
    cv::Mat binarize(const cv::Mat &src);

    // =====================================================================
    // 3.2 二值形态学基本运算
    // =====================================================================

    /**
     * 二值腐蚀 (式 3-9)
     * 式 3-9：A㊀B = { x | (B)x ⊆ A }，结构元素 B 平移 x 后完全含于 A 的
     * 原点位置集合。腐蚀缩小目标、消除小于结构元素的亮成分。
     *
     * @param ksize 结构元素边长（3/5/7…）
     * @param shape 0=矩形，1=圆形（椭圆）
     */
    cv::Mat binaryErode(const cv::Mat &src, int ksize, int shape);

    /**
     * 二值膨胀 (式 3-10, 式 3-11)
     * 式 3-10：A⊕B = { x | (B̂+x) ∩ A ≠ ∅ }（B̂ 为 B 的反射）
     * 式 3-11：A⊕B = { x | (B̂+x) ∩ A ⊆ A }（等价定义）
     * 膨胀扩大目标、桥接裂缝、填补孔洞。
     */
    cv::Mat binaryDilate(const cv::Mat &src, int ksize, int shape);

    /**
     * 二值开运算 (式 3-15, 式 3-16)
     * 式 3-15：A°B = (A㊀B)⊕B（先腐蚀后膨胀）
     * 式 3-16：A°B = ∪( B+x : B+x ⊆ A )（拟合集合解释）
     * 消除小于结构元素的亮噪声/毛刺，保持目标整体尺寸基本不变。
     */
    cv::Mat binaryOpen(const cv::Mat &src, int ksize, int shape);

    /**
     * 二值闭运算 (式 3-17)
     * 式 3-17：A·B = (A⊕B)㊀B（先膨胀后腐蚀）
     * 填补小于结构元素的暗孔洞/细缝，保持目标整体尺寸基本不变。
     */
    cv::Mat binaryClose(const cv::Mat &src, int ksize, int shape);

    /**
     * 膨胀与腐蚀的对偶性 (式 3-13, 式 3-14)
     * 式 3-13：(A⊕B)ᶜ = Aᶜ㊀B̂
     * 式 3-14：(A㊀B)ᶜ = Aᶜ⊕B̂
     * 本函数计算 Aᶜ㊀B̂（对补集腐蚀），结果理论上与 (A⊕B)ᶜ 完全相同，
     * 直观演示对偶关系（对称结构元素 B̂=B）。
     */
    cv::Mat binaryDuality(const cv::Mat &src, int ksize);

    // =====================================================================
    // 3.3 二值图像的形态学处理
    // =====================================================================

    /** 内边缘 (式 3-20)：β内(A) = A − (A㊀B)，目标收缩一侧的边缘。 */
    cv::Mat binaryInnerEdge(const cv::Mat &src, int ksize);

    /** 外边缘 (式 3-21)：β外(A) = (A⊕B) − A，目标外侧扩张一圈的边缘。 */
    cv::Mat binaryOuterEdge(const cv::Mat &src, int ksize);

    /** 形态学梯度边缘 (式 3-22)：β梯度(A) = (A⊕B) − (A㊀B)，宽度为 2 倍膨胀边缘。 */
    cv::Mat binaryGradientEdge(const cv::Mat &src, int ksize);

    /**
     * 区域填充 (式 3-23)
     * 式 3-23：Xk = (X(k-1)⊕B) ∩ Aᶜ，迭代至收敛，X0 取 Aᶜ 的边界种子点，
     * 收敛结果为外部背景；孔洞 = Aᶜ − X∞，填充结果 = A ∪ 孔洞。
     * 本实现按式 3-23 迭代（种子取图像边界上的背景点），等价于逐孔填充。
     */
    cv::Mat binaryFillHoles(const cv::Mat &src, int ksize);

    /**
     * 骨架抽取 (式 3-24 ~ 式 3-28)
     * 式 3-24：S(A) = ∪(n=0..N) Sn(A)，Sn(A) = (A㊀nB) − (A㊀nB)°B
     * 式 3-25：A㊀nB 为连续腐蚀 n 次
     * 式 3-26：N = max{ n | (A㊀nB) ≠ ∅ }（腐蚀为空前的最后一次迭代）
     * 式 3-27/3-28：A = ∪(Sn(A)⊕nB)（骨架可重建原图）
     * 输出单像素宽骨架，保持目标的拓扑结构。
     */
    cv::Mat binarySkeleton(const cv::Mat &src, int ksize);

    /**
     * 细化 (式 3-29 ~ 式 3-31)
     * 式 3-29：A⊗B = A − (A㊀B) = A∩(A㊀B)ᶜ（基于击中/击不中的定义，
     *          仅考虑前景模式匹配）
     * 式 3-30：{B} = {B1,B2,…,Bn}（Bi 为 Bi-1 旋转后的结构元素序列）
     * 式 3-31：A⊗{B} = ((…(A⊗B1)⊗B2)…)⊗Bn，循环扫描直到收敛
     * 本实现采用 Zhang-Suen 串行细化算法——它是式 3-31 旋转结构元素
     * 序列思想的经典串行实现，在逐步剥离边缘像素的同时保持连通性。
     */
    cv::Mat binaryThinning(const cv::Mat &src);

    /**
     * 形态开-闭滤波 (式 3-34)
     * 式 3-34：(A°B)·B = {[(A㊀B)⊕B]⊕B}㊀B（先开后闭）
     * 先开运算消除目标内部白色（前景）噪声，再闭运算消除目标周围
     * 黑色（背景）噪声。结构元素应比两种噪声的尺寸都大。
     */
    cv::Mat binaryOpenCloseFilter(const cv::Mat &src, int ksize);

    // =====================================================================
    // 3.4 灰度形态学基本运算
    // =====================================================================

    /**
     * 灰度腐蚀 (式 3-36, 式 3-37)
     * 式 3-36：(f㊀b)(s,t) = min{ f(s+x,t+y) − b(x,y) |
     *          (s+x,t+y)∈Df；(x,y)∈Db }
     * 式 3-37：一维简化形式 (f㊀b)(s) = min{ f(s+x) − b(x) }
     * 类似卷积但以最小值代替求和、以减法代替乘法。
     * 效果（图 3-30b）：整体变暗，小于结构元素的亮细节被削弱。
     */
    cv::Mat grayErode(const cv::Mat &src, int ksize, int shape);

    /**
     * 灰度膨胀 (式 3-38, 式 3-39)
     * 式 3-38：(f⊕b)(s,t) = max{ f(s−x,t−y) + b(x,y) |
     *          (s−x,t−y)∈Df；(x,y)∈Db }
     * 式 3-39：一维简化形式
     * 效果（图 3-30c）：整体变亮，小于结构元素的暗细节被削弱，边缘延伸。
     * 对偶关系（式 3-40/3-41）：(f㊀b)ᶜ = fᶜ⊕b̂，(f⊕b)ᶜ = fᶜ㊀b̂。
     */
    cv::Mat grayDilate(const cv::Mat &src, int ksize, int shape);

    /**
     * 灰度开运算 (式 3-42)
     * 式 3-42：f°b = (f㊀b)⊕b
     * 几何解释（图 3-31）：b 贴着 f 曲面上沿滚动，削平比 b 直径小的亮峰。
     * 用于消除小的亮细节（亮噪声），保持整体灰度与大的亮区域不变。
     */
    cv::Mat grayOpen(const cv::Mat &src, int ksize, int shape);

    /**
     * 灰度闭运算 (式 3-43)
     * 式 3-43：f·b = (f⊕b)㊀b
     * 几何解释（图 3-32）：b 贴着 f 曲面下沿滚动，填充比 b 直径小的暗谷。
     * 用于消除小的暗细节（暗噪声），保持整体灰度与明亮部分不变。
     * 对偶（式 3-44/3-45）：(f·b)ᶜ = fᶜ°b̂，(f°b)ᶜ = fᶜ·b̂。
     */
    cv::Mat grayClose(const cv::Mat &src, int ksize, int shape);

    // =====================================================================
    // 3.5 灰度图像的形态学处理
    // =====================================================================

    /**
     * 形态学梯度 (式 3-46)
     * 式 3-46：g = (f⊕b) − (f㊀b)
     * 增强图像中较尖锐的灰度过渡区，用于边缘提取。相比 Roberts/Sobel
     * 等差分算子，形态学梯度不会加强或放大噪声；使用对称结构元素
     * 时求得的边缘受方向影响较小。
     */
    cv::Mat grayMorphGradient(const cv::Mat &src, int ksize, int shape);

    /**
     * 形态开-闭平滑 (式 3-47)
     * 式 3-47：(f°b)·b = {[(f㊀b)⊕b]⊕b}㊀B
     * 开运算去亮噪声 + 闭运算去暗噪声的组合滤波器。
     */
    cv::Mat grayOpenClose(const cv::Mat &src, int ksize, int shape);

    /**
     * 形态闭-开平滑 (式 3-48)
     * 式 3-48：(f·b)°b = {[(f⊕b)㊀b]㊀b}⊕b
     * 与开-闭互为对偶次序的组合滤波器，两者平均可得更平滑效果。
     */
    cv::Mat grayCloseOpen(const cv::Mat &src, int ksize, int shape);

    /**
     * 高帽 Top-Hat 变换 (式 3-49)
     * 式 3-49：h = f − (f°b)
     * 开运算非扩展性（结构元素始终处于图像下方）保证结果非负。
     * 检测图像中较尖锐的波峰：从暗而平滑的背景中提取亮细节，
     * 如增强阴影部分细节、目标分割、波峰波谷检测等。
     */
    cv::Mat grayTopHat(const cv::Mat &src, int ksize, int shape);

    /**
     * 低帽 Bottom-Hat 变换 (表 3-1 bothat)
     * bh = (f·b) − f
     * 闭运算为扩展运算（结果始终在图像上方），故差值非负。
     * 检测图像中的波谷：提取暗细节/暗结构（MATLAB 表 3-1 bothat）。
     */
    cv::Mat grayBottomHat(const cv::Mat &src, int ksize, int shape);

    /**
     * Top-Hat 增强（式 3-49 的应用组合）
     * g = f + TopHat(f) − BottomHat(f)
     * 高帽提升亮细节、低帽抑制暗细节，组合后图像对比度与细节
     * 显著增强（对阴影区细节增强尤其有效）。
     */
    cv::Mat grayTopHatEnhance(const cv::Mat &src, int ksize, int shape);
}

#endif //OPENCVDEAL_IMAGEMORPHOLOGY_H
