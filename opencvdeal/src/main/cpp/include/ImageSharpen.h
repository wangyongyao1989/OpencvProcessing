#ifndef OPENCVDEAL_IMAGESHARPEN_H
#define OPENCVDEAL_IMAGESHARPEN_H

#include <opencv2/core.hpp>

/**
 * 图像锐化
 *
 * 基于《数字图像与视频处理》第二章 2.4 节"图像锐化"实现：
 * - 梯度运算（算子）(2.4.1)：水平垂直差分法、Roberts 梯度
 * - Sobel 算子 (2.4.2)
 * - 拉普拉斯算子 (2.4.3)：H1 模板与合成拉普拉斯模板 H6/H7
 * - 频率域高通滤波 (2.4.4)：理想高通、高斯高通
 */
namespace ImageSharpen {

    /**
     * 水平垂直差分法 (式 2-54 ~ 式 2-56, 输出式 2-58)
     * 式 2-54：G[f(x,y)] = [∂f/∂x, ∂f/∂y]^T = [Gx, Gy]^T（梯度定义）
     * 式 2-55：G[f(x,y)] = √(Gx² + Gy²)（梯度幅度，各向同性）
     * 式 2-56：G[f(i,j)] = |f(i+1,j) − f(i,j)| + |f(i,j+1) − f(i,j)|
     *          （用绝对值代替平方和开方以降低运算量）
     * 式 2-58：g(i,j) = G[f(i,j)]（输出灰度等于梯度幅度）
     * 梯度值与相邻像素灰度差成正比：边缘区大、平缓区小、均匀区为零，
     * 故输出仅留下灰度急剧变化的边缘点（图 2-33b）。
     * 注：最后一行/列无法直接求梯度，用前一行/列梯度值近似代替。
     *
     * @param src 输入图像（内部先转为灰度）
     */
    cv::Mat gradientHorizVert(const cv::Mat &src);

    /**
     * Roberts 梯度（交叉差分法）(式 2-57, 输出式 2-58)
     * 式 2-57：G[f(i,j)] = |f(i+1,j+1) − f(i,j)| + |f(i,j+1) − f(i+1,j)|
     * 采用 2×2 窗口的交叉差分运算。对陡峭边缘响应强、定位精度高，
     * 但无平均因素，抗噪声能力差。
     *
     * @param src 输入图像（内部先转为灰度）
     */
    cv::Mat robertsGradient(const cv::Mat &src);

    /**
     * Sobel 算子锐化 (式 2-63 ~ 式 2-66)
     * 式 2-63：Gx = [f(i+1,j−1)+2f(i+1,j)+f(i+1,j+1)]
     *              − [f(i−1,j−1)+2f(i−1,j)+f(i−1,j+1)]
     * 式 2-64：Gy = [f(i−1,j+1)+2f(i,j+1)+f(i+1,j+1)]
     *              − [f(i−1,j−1)+2f(i,j−1)+f(i+1,j−1)]
     * 式 2-65：Hx = [[−1,0,1],[−2,0,2],[−1,0,1]]，
     *          Hy = [[−1,−2,−1],[0,0,0],[1,2,1]]
     * 式 2-66：g(i,j) = √(Gx² + Gy²)；为简化计算可用 g = |Gx| + |Gy|（本实现采用）
     * 引入平均因素对随机噪声有一定平滑作用；相隔两行/两列之差分使
     * 边缘两侧元素同时得到增强，边缘显得粗而亮。
     *
     * @param src 输入图像（内部先转为灰度）
     */
    cv::Mat sobelOperator(const cv::Mat &src);

    /**
     * 拉普拉斯直接锐化（模板 H1）(式 2-67 ~ 式 2-71)
     * 式 2-67：∇²f = ∂²f/∂x² + ∂²f/∂y²（二阶偏导线性组合，各向同性）
     * 式 2-68：∂²f/∂x² ≈ f(i+1,j) + f(i−1,j) − 2f(i,j)
     * 式 2-69：∂²f/∂y² ≈ f(i,j+1) + f(i,j−1) − 2f(i,j)
     * 式 2-70：∇²f = f(i+1,j) + f(i−1,j) + f(i,j+1) + f(i,j−1) − 4f(i,j)
     * 式 2-71：模板 H1 = [[0,1,0],[1,−4,1],[0,1,0]]
     * 直接锐化后边缘增强，但背景信息消失（图 2-36）。
     *
     * @param src 输入图像（内部先转为灰度）
     */
    cv::Mat laplacianDirect(const cv::Mat &src);

    /**
     * 合成拉普拉斯锐化（模板 H6，k=1）(式 2-72 ~ 式 2-74)
     * 式 2-72：g(i,j) = f(i,j) − k∇²f（k 与扩散效应有关，太大过冲，太小不明显）
     * 式 2-73：k=1 时 g(i,j) = 5f(i,j) − f(i+1,j) − f(i−1,j)
     *                       − f(i,j+1) − f(i,j−1)
     * 式 2-74：模板 H6 = [[0,−1,0],[−1,5,−1],[0,−1,0]]
     * 将原图与拉普拉斯锐化结果叠加，既体现锐化效果又保留背景信息（图 2-37）。
     *
     * @param src 输入图像（内部先转为灰度）
     */
    cv::Mat laplacianCompositeH6(const cv::Mat &src);

    /**
     * 合成拉普拉斯锐化（模板 H7，8 邻域版本）
     * H7 = [[−1,−1,−1],[−1,9,−1],[−1,−1,−1]]
     * H6~H9 统称合成拉普拉斯模板；H7 为 8 邻域形式（中心 9 = 1 + 8），
     * 边缘与纹理的增强比 4 邻域的 H6 更强（图 2-37）。
     *
     * @param src 输入图像（内部先转为灰度）
     */
    cv::Mat laplacianCompositeH7(const cv::Mat &src);

    /**
     * 理想高通滤波锐化 (式 2-75, 式 2-76；流程式 2-40)
     * 式 2-75：H(u,v) = 1,  D(u,v) > D0；   0,  D(u,v) ≤ D0
     * 式 2-76：D(u,v) = √(u² + v²)（频率点到频率平面原点的距离）
     * 流程：DFT 得到边缘信息（高频分量）→ 将高频边缘附加到原图实现锐化
     * （g = f + 高频边缘）。H 从 0 到 1 陡峭突变，滤波结果存在"振铃"现象。
     *
     * @param src 输入图像（内部先转为灰度）
     * @param D0  截止频率（频率平面像素距离）
     */
    cv::Mat idealHighPassSharpen(const cv::Mat &src, double D0);

    /**
     * 高斯高通滤波锐化 (式 2-79)
     * 式 2-79：H(u,v) = 1 − e^(−D²(u,v)/(2D0²))
     * 高低频之间平滑过渡，无振铃现象；D0 增大时增强效果更明显。
     * 同样将高通得到的边缘信息附加到原图实现锐化。
     *
     * @param src 输入图像（内部先转为灰度）
     * @param D0  截止频率
     */
    cv::Mat gaussianHighPassSharpen(const cv::Mat &src, double D0);
}

#endif //OPENCVDEAL_IMAGESHARPEN_H
